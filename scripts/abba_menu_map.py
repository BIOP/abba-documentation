"""Extract the user-facing menus of the ABBA window from the ijp-imagetoatlas sources.

scijava-introspect reports each command's Fiji menu path, but ABBA users launch
commands from the menu bar of the ABBA window, which BdvMultislicePositionerView
builds by hand. This script reads that file (and the right-click popup menu) at a
given git tag and prints, in menu order:

  - the menu bar entries: menu path -> command class, or (action) for plain actions
  - the right-click popup entries on slices
  - the names of the cards of the side panel

Usage:
  python scripts/abba_menu_map.py <ijp-imagetoatlas repo> <tag> > cli-outputs/<version>/menu-abba-window.txt
"""
import re
import subprocess
import sys

VIEW = "src/main/java/ch/epfl/biop/atlas/aligner/gui/bdv/BdvMultislicePositionerView.java"
POPUP = "src/main/java/ch/epfl/biop/atlas/aligner/gui/SliceSourcesPopupMenu.java"

COMMAND = re.compile(r'addCommandToBdvHandleMenu\(\s*bdvh\s*,[^,]+,\s*"([^"]+)"\s*,\s*(\w+)\.class')
ACTION = re.compile(r'addActionToBdvHandleMenu\(\s*bdvh\s*,\s*"([^"]+)"')
SEPARATOR = re.compile(r'addSeparator\(\s*bdvh\s*,\s*"([^"]+)"')
CARD_NAME = re.compile(r'NAME_CARD_\w+\s*=\s*"([^"]+)"')
POPUP_ACTION = re.compile(r'addPopupAction\((?:\s*popup\s*,)?\s*"([^"]+)"')


def show(repo, tag, path):
    return subprocess.run(["git", "-C", repo, "show", f"{tag}:{path}"],
                          capture_output=True, text=True, encoding="utf-8", check=True).stdout


def main(repo, tag):
    view = show(repo, tag, VIEW)
    # The menu bar is built by installBdvMenu and installRegistrationPluginUI: scanning the
    # whole file in order keeps their entries in installation order.
    menu = view

    print(f"# ABBA window menus at {tag}")
    print(f"# Generated by scripts/abba_menu_map.py from {VIEW}")
    print()
    print("## Menu bar (menu order as installed; (action) = not a SciJava command)")
    print("## Registration plugins discovered at runtime and ABBACommand plugins are added on top of these.")
    seen = set()
    for line in menu.splitlines():
        stripped = line.strip()
        if stripped.startswith("//"):
            continue
        m = COMMAND.search(line)
        if m:
            entry = f"{m.group(1)}  ->  {m.group(2)}"
        else:
            m = ACTION.search(line)
            if m and m.group(1).endswith(">"):
                continue  # "Register>" + name: external registration plugins, known at runtime only
            if m:
                entry = f"{m.group(1)}  ->  (action)"
            elif SEPARATOR.search(line):
                continue
            else:
                continue
        if entry not in seen:  # mouse and rat variants of DeepSlice repeat the same entries
            seen.add(entry)
            print(entry)

    print()
    print("## Right-click popup menu on slices")
    try:
        popup = show(repo, tag, POPUP)
        # Labels built with a slice count ("Remove Selected Slices (" + n + ")") are cut at " (".
        names = (m.group(1).strip().rstrip(" (") for m in POPUP_ACTION.finditer(popup))
        for name in dict.fromkeys(names):
            print(name)
    except subprocess.CalledProcessError:
        print("(popup source not found at this tag)")

    print()
    print("## Side panel cards")
    for name in CARD_NAME.findall(view):
        print(name)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.stdout.reconfigure(encoding="utf-8")
    main(sys.argv[1], sys.argv[2])
